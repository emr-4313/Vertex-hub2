import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_FILES_DIRECTORY = path.join(ROOT, "public", "files");
const DEFAULT_OUTPUT_FILE = path.join(ROOT, "src", "data", "generated-places.ts");

export function createPlaceRecord(fileName, bytes) {
  const extension = fileName.match(/\.(rbxl|rbxm)$/i)?.[1]?.toLowerCase();
  if (!extension || path.basename(fileName) !== fileName) return null;

  const name = fileName
    .replace(/\.(rbxl|rbxm)$/i, "")
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  return {
    id: fileName,
    name,
    file: fileName,
    downloadName: fileName,
    bytes,
    ext: extension,
  };
}

export async function generatePlaceCatalog(
  filesDirectory = DEFAULT_FILES_DIRECTORY,
  outputFile = DEFAULT_OUTPUT_FILE,
) {
  const entries = await readdir(filesDirectory, { withFileTypes: true });
  const records = (await Promise.all(
    entries
      .filter((entry) => entry.isFile())
      .map(async (entry) => {
        const filePath = path.join(filesDirectory, entry.name);
        const { size } = await stat(filePath);
        return createPlaceRecord(entry.name, size);
      }),
  ))
    .filter(Boolean)
    .sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base", numeric: true }));

  const source =
    "// Generated by scripts/generate-place-catalog.mjs. Do not edit by hand.\n" +
    "export const GENERATED_PLACES = " +
    JSON.stringify(records, null, 2) +
    " as const;\n";

  let previous = "";
  try {
    previous = await readFile(outputFile, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (previous !== source) await writeFile(outputFile, source, "utf8");
  return records;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const records = await generatePlaceCatalog();
  console.log("Generated catalog with " + records.length + " Roblox files.");
}
